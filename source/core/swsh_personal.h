inline const Entry* FindSwsh(std::uint16_t dex, std::uint8_t form) {
  const std::size_t n = sizeof(kSwSh) / sizeof(kSwSh[0]);
  for (std::size_t i = 0; i < n; ++i)
    if (kSwSh[i].dex == dex && kSwSh[i].form == form) return &kSwSh[i];
  return nullptr;
}


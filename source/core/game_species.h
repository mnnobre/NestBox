// A especie existe nos dados deste jogo? E a regra central da secao 7
// da pesquisa: nao depende do progresso da Pokedex do jogador.
inline bool HasSpecies(Game game, int dex) {
  if (dex <= 0 || dex > kMaxDex) return false;
  const std::size_t g = static_cast<std::size_t>(game);
  if (g >= static_cast<std::size_t>(Game::kCount)) return false;
  return (kGameSpecies[g][dex / 64] >> (dex % 64)) & 1ULL;
}

inline const char* GameName(Game game) {
  const std::size_t g = static_cast<std::size_t>(game);
  if (g >= static_cast<std::size_t>(Game::kCount)) return "";
  return kGameNames[g];
}

inline std::size_t SpeciesCount(Game game) {
  const std::size_t g = static_cast<std::size_t>(game);
  if (g >= static_cast<std::size_t>(Game::kCount)) return 0;
  return kGameSpeciesCount[g];
}


// Busca linear: a tabela e pequena e o gerador roda uma vez por lote.
inline const Entry* FindLgpe(std::uint16_t dex, std::uint8_t form) {
  const std::size_t n = sizeof(kLgpe) / sizeof(kLgpe[0]);
  for (std::size_t i = 0; i < n; ++i)
    if (kLgpe[i].dex == dex && kLgpe[i].form == form) return &kLgpe[i];
  return nullptr;
}


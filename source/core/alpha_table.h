inline constexpr std::size_t kCount = sizeof(kPares) / sizeof(kPares[0]);

// O PLA e o unico jogo com a mecanica; para os outros a resposta e sempre
// false, e quem chama nao precisa saber disso.
inline bool TemVariante(std::uint16_t dex, std::uint8_t form) {
  for (std::size_t i = 0; i < kCount; ++i)
    if (kPares[i].dex == dex && kPares[i].form == form) return true;
  return false;
}


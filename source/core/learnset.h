struct Table {
  const Entry* entries;
  std::size_t entry_count;
  const Index* index;
  std::size_t index_count;
};

inline constexpr Table kTables[] = {
    {kEntriesLegendsArceus, sizeof(kEntriesLegendsArceus) / sizeof(Entry),
     kIndexLegendsArceus, sizeof(kIndexLegendsArceus) / sizeof(Index)},
    {kEntriesBdsp, sizeof(kEntriesBdsp) / sizeof(Entry),
     kIndexBdsp, sizeof(kIndexBdsp) / sizeof(Index)},
};

// Faixa de pares (nivel, golpe) da especie/forma neste jogo. Devolve false se
// a especie nao existe no jogo (ou nao aprende nada por nivel).
inline bool Find(Game game, std::uint16_t species, std::uint8_t form,
                 const Entry** out, std::size_t* count) {
  const std::size_t g = static_cast<std::size_t>(game);
  if (g >= static_cast<std::size_t>(Game::kCount)) return false;
  const Table& t = kTables[g];
  for (std::size_t i = 0; i < t.index_count; ++i) {
    if (t.index[i].species == species && t.index[i].form == form) {
      *out = t.entries + t.index[i].begin;
      *count = t.index[i].end - t.index[i].begin;
      return true;
    }
  }
  return false;
}

// Em que nivel a especie aprende este golpe? 0 se nao aprende por nivel.
inline std::uint8_t LevelOf(Game game, std::uint16_t species, std::uint8_t form,
                            std::uint16_t move) {
  const Entry* e = nullptr;
  std::size_t n = 0;
  if (!Find(game, species, form, &e, &n)) return 0;
  for (std::size_t i = 0; i < n; ++i)
    if (e[i].move == move) return e[i].level;
  return 0;
}

// Os quatro golpes que o Pokemon teria ao ser resetado por nivel: os quatro
// ultimos aprendidos ate `level`. E a regra da §7 da pesquisa da HOME.
//
// Spec 071 — o desempate foi conferido contra o PKHeX.Core
// (`Learnset.SetEncounterMoves`, 14.032 combinacoes especie×forma×nivel de PLA
// e BDSP, por tools/pkhex-moveset). O empate no MESMO nivel bate exatamente:
// oldest→newest na ordem da tabela. Mas a conferencia achou duas divergencias
// de outra natureza:
//
// 1. **Nivel 0** na tabela do PkHeX nao e "aprende ao nascer" — e golpe que so
//    vem por evolucao ou relearn (o 93 do Cloyster, o 352 do Gyarados). O
//    PkHeX os exclui do reset por nivel; nos os incluiamos porque `0 <= level`
//    e sempre verdadeiro. Eram 134 linhas divergentes.
//
// 2. **A ordem e a da TABELA, e o corte e um `break`, nao um `continue`.**
//    O PkHeX percorre o array e PARA no primeiro golpe de nivel acima do alvo;
//    nao filtra o array inteiro. A diferenca so aparece quando a tabela sai da
//    ordem, o que acontece em exatamente UMA faixa nas duas tabelas (conferido
//    exaustivamente): o Dragonite (149) do BDSP tem `{41,200}` depois de
//    `{62,349}`.
//
//    Consequencia observada no proprio PkHeX: `SetEncounterMoves(41)` do
//    Dragonite **nao** inclui o golpe 200, apesar de ele ser de nivel 41 —
//    porque a varredura ja parou no `{46,219}`. Ordenar por nivel
//    "consertaria" isso e divergiria do jogo: tentado, subiu de 3 para 6
//    divergencias. O dado manda, nao a intuicao.
//
// Com as duas correcoes: ZERO divergencias. Fecha a pendencia 4 do
// evidence-log da spec 065. NAO reverter sem rodar tools/pkhex-moveset.
inline int MovesAtLevel(Game game, std::uint16_t species, std::uint8_t form,
                        std::uint8_t level, std::uint16_t out[4]) {
  for (int i = 0; i < 4; ++i) out[i] = 0;
  const Entry* e = nullptr;
  std::size_t n = 0;
  if (!Find(game, species, form, &e, &n)) return 0;
  int count = 0;
  for (std::size_t i = 0; i < n; ++i) {
    // Para no primeiro acima do alvo — o PkHeX faz assim, e a ordem da tabela
    // e que manda (ver o comentario acima).
    if (e[i].level > level) break;
    // Nivel 0 = golpe de evolucao/relearn, nao entra no reset por nivel.
    if (e[i].level == 0) continue;
    // Ja tem esse golpe? Nao duplica.
    bool dup = false;
    for (int k = 0; k < count; ++k)
      if (out[k] == e[i].move) dup = true;
    if (dup) continue;
    if (count < 4) {
      out[count++] = e[i].move;
    } else {
      out[0] = out[1];
      out[1] = out[2];
      out[2] = out[3];
      out[3] = e[i].move;
    }
  }
  return count;
}


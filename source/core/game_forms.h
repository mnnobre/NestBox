// A (especie, forma) existe nos dados deste jogo?
//
// Jogo sem tabela medida devolve TRUE: a ausencia de dado nao pode virar
// bloqueio: isso reprovaria transferencia legal para todo jogo pre-Switch.
// Quem barra ali continua sendo HasSpecies.
inline bool HasForm(Game game, int dex, int form) {
  if (dex <= 0 || dex > kMaxDex || form < 0 || form >= 64) return false;
  const std::size_t g = static_cast<std::size_t>(game);
  if (g >= static_cast<std::size_t>(Game::kCount)) return false;
  const FormTable& t = kGameForms[g];
  if (t.keys == nullptr) return true;  // sem dado medido: nao bloqueia
  const std::uint32_t want = static_cast<std::uint32_t>(dex) * 64u +
                             static_cast<std::uint32_t>(form);
  std::size_t lo = 0, hi = t.count;
  while (lo < hi) {
    const std::size_t mid = lo + (hi - lo) / 2;
    if (t.keys[mid] < want) lo = mid + 1;
    else hi = mid;
  }
  return lo < t.count && t.keys[lo] == want;
}


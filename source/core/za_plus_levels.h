// O nivel em que a flag do golpe `i` da faixa daquela (especie,forma) passa a
// ser cobrada. `i` e o MESMO indice do array devolvido por learnset::Find —
// as duas listas sao paralelas.
//
// Devolve 0 se a faixa nao existe: 0 nunca e um nivel plus valido (o menor
// medido e 6), entao o chamador pode trata-lo como "sem cobranca".
inline std::uint8_t Nivel(const learnset::Entry* base, std::size_t i) {
  const learnset::Table& t =
      learnset::kTables[static_cast<std::size_t>(learnset::Game::kZA)];
  // `base` aponta para dentro de kEntriesZA; a distancia ate o inicio e o
  // indice no array paralelo.
  if (base < t.entries) return 0;
  const std::size_t off = static_cast<std::size_t>(base - t.entries) + i;
  if (off >= sizeof(kLevels) / sizeof(kLevels[0])) return 0;
  return kLevels[off];
}


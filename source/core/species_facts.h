// Especies FUSIONAVEIS. Fonte: PKHeX.Core
// Bulk.DuplicateFusionChecker.GetIndexFusedStorage(dex, form) devolve >= 0
// exatamente para estas — varredura das 1025, nao lista escrita a mao:
//   646 Kyurem
//   800 Necrozma
//   898 Calyrex
inline constexpr std::uint16_t kFusableSpecies[3] = {
    646,800,898,
};

// Tipo primario da especie. 0xFF se o numero nao e uma especie valida —
// nunca 0, que e Normal e seria confundido com dado bom.
inline std::uint8_t Type1(int dex) {
  if (dex <= 0 || dex > kMaxDex) return 0xFF;
  return kType1[dex];
}

// Lendario, sub-lendario ou mitico? E o grupo que o BDSP limita a um por save.
inline bool IsLegendary(int dex) {
  if (dex <= 0 || dex > kMaxDex) return false;
  return kIsLegendary[dex] != 0;
}

// Nivel a partir da experiencia (spec 076, pendencia P-03 da spec 070).
//
// O nivel NAO esta gravado no PKM dos formatos modernos: ele deriva da exp
// pela curva de crescimento da especie. Ate a spec 076 so existia tabela de
// curva para o gen3, e quem chamava as regras de transferencia passava o
// nivel na mao — com 0 significando "desconhecido", que fazia a regra do
// Hyper Training do BDSP sumir em silencio.
//
// 0 se a especie nao e valida: nesse caso NAO ha nivel, e devolver 1 seria
// inventar dado. Quem chama tem de tratar o 0.
inline std::uint8_t LevelFromExp(int dex, std::uint32_t exp) {
  if (dex <= 0 || dex > kMaxDex) return 0;
  const std::uint32_t* row = kExpToLevel[kGrowthRate[dex]];
  // Do topo para baixo: o nivel e o maior cuja exp minima ja foi atingida.
  for (int lv = 100; lv >= 1; --lv) {
    if (exp >= row[lv]) return static_cast<std::uint8_t>(lv);
  }
  return 1;  // exp abaixo do nivel 1 nao existe no jogo; nivel 1 e o piso.
}

// Esta (especie, forma) e uma FUSAO?
//
// §7 da pesquisa: "fusoes precisam ser desfeitas antes de depositar". A forma
// 0 e a base — Kyurem solto, Necrozma normal, Calyrex sozinho — e ESSA entra
// normalmente. Fundido e a forma 1 ou 2.
inline bool IsFusedForm(int dex, int form) {
  if (form != 1 && form != 2) return false;
  for (std::uint16_t d : kFusableSpecies) {
    if (d == dex) return true;
  }
  return false;
}

// HP maximo pela formula padrao (spec 119). Um lugar so: a cauda de party do
// save e o HP atual do nucleo precisam do MESMO numero, e duas copias da
// formula divergiriam em silencio.
//
// Shedinja (base 1) tem HP 1 sempre. Dex invalida devolve 0.
inline std::uint16_t MaxHp(int dex, std::uint8_t iv, std::uint8_t ev,
                           std::uint8_t level) {
  if (dex <= 0 || dex > 1025 || level == 0) return 0;
  const std::uint8_t base = modern::kBaseStats[dex][0];
  if (base == 1) return 1;
  return static_cast<std::uint16_t>((2 * base + iv + ev / 4) * level / 100 +
                                    level + 10);
}


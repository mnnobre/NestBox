// Os bytes-molde daquele formato, ou {nullptr,0} se nao houver.
// O gerador NAO deve seguir sem molde: montar do zero e o bug que este
// arquivo existe para impedir.
inline const std::uint8_t* Bytes(pkm::Format f, std::size_t* n) {
  for (const Molde& m : kMoldes) {
    if (m.formato == f) {
      if (n) *n = m.n;
      return m.dados;
    }
  }
  if (n) *n = 0;
  return nullptr;
}


// GERADO por tools/pkhex-molde - nao editar a mao (spec 144, TD-04).
//
// Um registro-molde por formato. O gerador de Pokemon NUNCA parte de bytes
// zerados: ele carrega o molde do formato de destino e escreve por cima so os
// campos que o jogador escolheu.
//
// Por que isso existe: `Write()` parte de `p.raw` e, com raw vazio, produz um
// buffer zerado — deixando em zero todo offset que o `Parse` ainda nao mapeia
// (o header do PA8 avisa que 20 deles sao derivados por analogia e nao
// verificados). Foi assim que, numa rodada anterior deste projeto, a suite
// inteira passou e no jogo real todos os Pokemon viraram ovo.
//
// Cada molde foi montado pelos SETTERS do PKHeX.Core e aprovado pelo
// LegalityAnalysis do proprio PkHeX antes de virar bytes aqui.
//
// A identidade e NEUTRA de proposito (OT vazio, TID/SID 0, sem apelido, sem
// fita, sem memoria): nada de save real do dono entra no repo, e todo campo
// de identidade e sobrescrito pelo gerador.
